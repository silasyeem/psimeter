#!/bin/sh
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
env_file="$root/.env"
secrets="$root/Config/Secrets.xcconfig"

token=""
note=""
if [ -f "$env_file" ]; then
  raw=$(sed -n -E 's/^[[:space:]]*(export[[:space:]]+)?WAQI_TOKEN[[:space:]]*=[[:space:]]*//p' "$env_file" | tail -n 1 | tr -d '\r')
  case $raw in
    \"*) token=${raw#\"}; token=${token%%\"*} ;;
    \'*) token=${raw#\'}; token=${token%%\'*} ;;
    *) token=${raw%%[[:space:]#]*} ;;
  esac
fi

# An xcconfig reads "//" as a comment and "$(" as a variable, so only a plain token survives the trip.
case $token in
  *[!A-Za-z0-9._-]*) token=""; note=" (the .env value has characters a token cannot contain)" ;;
esac

umask 077
tmp=$(mktemp "$secrets.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
  echo "// Generated by scripts/sync-secrets.sh from .env. Edit .env, not this file."
  echo "WAQI_TOKEN = $token"
} > "$tmp"

if cmp -s "$tmp" "$secrets"; then
  rm -f "$tmp"
else
  mv "$tmp" "$secrets"
fi

if [ -n "$token" ]; then
  echo "WAQI token: set"
else
  echo "WAQI token: empty$note"
fi
